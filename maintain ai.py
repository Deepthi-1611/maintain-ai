def retrieve_hybrid_evidence(
    query,
    fault_hypothesis=None,
    top_k=3
):
    """
    Hybrid retrieval combining:
    1. Semantic similarity
    2. Knowledge-graph/fault relevance
    3. Document relevance

    Scores are prototype ranking weights for
    the academic demonstration.
    """

    # ----------------------------------------
    # Semantic retrieval
    # ----------------------------------------

    semantic_results = retrieve_maintenance_evidence(
        query=query,
        top_k=len(rag_chunks)
    )

    preferred_docs = set(
        FAULT_DOCUMENT_MAP.get(
            fault_hypothesis,
            []
        )
    )

    reranked = []

    for item in semantic_results:

        semantic_score = float(
            item["score"]
        )

        # ------------------------------------
        # Knowledge relevance bonus
        # ------------------------------------

        if item["doc_id"] in preferred_docs:
            knowledge_bonus = 0.25
        else:
            knowledge_bonus = 0.0

        # ------------------------------------
        # Fault-name keyword bonus
        # ------------------------------------

        keyword_bonus = 0.0

        if fault_hypothesis:

            fault_terms = (
                fault_hypothesis
                .replace("Fault", "")
                .replace("Wear", " wear")
                .replace("Overload", " overload")
                .replace("Transmission", " transmission")
                .lower()
                .split()
            )

            text_lower = item["text"].lower()

            matching_terms = sum(
                1
                for term in fault_terms
                if term and term in text_lower
            )

            keyword_bonus = min(
                matching_terms * 0.05,
                0.15
            )

        # ------------------------------------
        # Final hybrid score
        # ------------------------------------

        hybrid_score = (
            0.65 * semantic_score
            + 0.25 * knowledge_bonus
            + 0.10 * keyword_bonus
        )

        reranked.append({
            **item,
            "semantic_score": round(
                semantic_score,
                4
            ),
            "knowledge_bonus": round(
                knowledge_bonus,
                4
            ),
            "keyword_bonus": round(
                keyword_bonus,
                4
            ),
            "hybrid_score": round(
                hybrid_score,
                4
            )
        })

    # Rank using hybrid score
    reranked.sort(
        key=lambda x: x["hybrid_score"],
        reverse=True
    )

    # Update ranks
    final_results = []

    for rank, item in enumerate(
        reranked[:top_k],
        start=1
    ):

        result = dict(item)
        result["rank"] = rank
        final_results.append(result)

    return final_results


