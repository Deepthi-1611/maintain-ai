# ------------------------------------------------
# A* heuristic
# ------------------------------------------------

NODE_HEURISTIC = {
    "Symptom": 2,
    "Fault": 1,
    "MaintenanceAction": 0
}


def diagnostic_heuristic(node, goal):
    """
    Simple admissible-style heuristic for our
    prototype diagnostic graph.

    The goal is always a maintenance action.
    """

    if node == goal:
        return 0

    # Use semantic distance based on node role.
    if node in KG.nodes:
        category = KG.nodes[node].get(
            "category",
            None
        )

        if category == "Symptom":
            return 2

        if category == "Fault":
            return 1

        if category == "MaintenanceAction":
            return 0

    return 1


# ------------------------------------------------
# Find diagnostic paths using A*
# ------------------------------------------------

def find_diagnostic_paths(
    symptoms,
    max_paths=5
):
    """
    Search for likely diagnostic action paths
    using A* Search.

    Returns:
        Ranked list of candidate paths.
    """

    candidate_paths = []

    for symptom in symptoms:

        if symptom not in DIAGNOSTIC_GRAPH:
            continue

        # Candidate faults from the knowledge graph
        possible_faults = kg_find_faults_from_symptom(
            symptom
        )

        for fault_item in possible_faults:

            fault = fault_item["fault"]

            if fault not in DIAGNOSTIC_GRAPH:
                continue

            actions = kg_find_actions_for_fault(
                fault
            )

            for action_item in actions:

                action = action_item["action"]

                if action not in DIAGNOSTIC_GRAPH:
                    continue

                try:
                    path = nx.astar_path(
                        DIAGNOSTIC_GRAPH,
                        symptom,
                        action,
                        heuristic=lambda current, goal: diagnostic_heuristic(
                            current,
                            goal
                        ),
                        weight="weight"
                    )

                    path_cost = nx.path_weight(
                        DIAGNOSTIC_GRAPH,
                        path,
                        weight="weight"
                    )

                    candidate_paths.append({
                        "symptom": symptom,
                        "fault": fault,
                        "action": action,
                        "path": path,
                        "cost": path_cost
                    })

                except nx.NetworkXNoPath:
                    continue

    # Remove duplicate paths
    unique_paths = {}

    for result in candidate_paths:
        key = tuple(result["path"])
        unique_paths[key] = result

    candidate_paths = list(
        unique_paths.values()
    )

    # Lower cost first
    candidate_paths.sort(
        key=lambda item: item["cost"]
    )

    return candidate_paths[:max_paths]


