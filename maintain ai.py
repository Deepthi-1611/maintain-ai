def bayesian_fault_inference(observed_evidence):
    """
    Estimate posterior fault probabilities using a
    simplified Naive-Bayes-style diagnostic model.

    Formula:
        P(F|E) ∝ P(F) × product(P(E_i|F))

    The evidence variables are treated as conditionally
    independent given the fault hypothesis.
    """

    # Validate evidence
    valid_evidence = [
        evidence
        for evidence in observed_evidence
        if evidence in EVIDENCE_LIKELIHOODS
    ]

    if not valid_evidence:
        raise ValueError(
            "No valid evidence supplied. "
            f"Available evidence: {list(EVIDENCE_LIKELIHOODS.keys())}"
        )

    # Calculate unnormalized posterior scores
    scores = {}

    for fault, prior in FAULT_PRIORS.items():

        score = prior

        for evidence in valid_evidence:
            likelihood = EVIDENCE_LIKELIHOODS[
                evidence
            ][fault]

            score *= likelihood

        scores[fault] = score

    # Normalize
    total_score = sum(scores.values())

    posterior = {
        fault: score / total_score
        for fault, score in scores.items()
    }

    # Sort highest probability first
    posterior = dict(
        sorted(
            posterior.items(),
            key=lambda item: item[1],
            reverse=True
        )
    )

    return posterior


def explain_bayesian_result(
    observed_evidence,
    posterior
):
    """
    Create a structured explanation of the Bayesian result.
    """

    top_fault = next(iter(posterior))
    top_probability = posterior[top_fault]

    return {
        "observed_evidence": observed_evidence,
        "most_likely_fault": top_fault,
        "probability": round(top_probability, 4),
        "probability_percent": round(
            top_probability * 100,
            2
        ),
        "all_fault_probabilities": {
            fault: round(probability * 100, 2)
            for fault, probability in posterior.items()
        },
        "model_note": (
            "Prototype Bayesian model using illustrative "
            "priors and likelihoods. Results are for academic "
            "decision-support demonstration and are not "
            "validated industrial diagnostic probabilities."
        )
    }


