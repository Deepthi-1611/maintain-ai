import pandas as pd

def predict_machine_condition(
    machine_type,
    air_temperature,
    process_temperature,
    rotational_speed,
    torque,
    tool_wear
):
    """
    Predict machine failure risk using the trained ML pipeline.

    Returns a structured dictionary that later AI agents
    can consume.
    """

    # Create a single-row DataFrame
    machine_input = pd.DataFrame([{
        "Type": machine_type,
        "Air temperature": air_temperature,
        "Process temperature": process_temperature,
        "Rotational speed": rotational_speed,
        "Torque": torque,
        "Tool wear": tool_wear
    }])

    # Prediction
    failure_prediction = int(
        ML_PIPELINE.predict(machine_input)[0]
    )

    # Failure probability
    failure_probability = float(
        ML_PIPELINE.predict_proba(machine_input)[0][1]
    )

    # Risk category
    if failure_probability >= 0.70:
        risk_level = "HIGH"
    elif failure_probability >= 0.40:
        risk_level = "MEDIUM"
    else:
        risk_level = "LOW"

    result = {
        "machine_type": machine_type,
        "predicted_failure": failure_prediction,
        "failure_probability": round(failure_probability, 4),
        "failure_probability_percent": round(
            failure_probability * 100, 2
        ),
        "risk_level": risk_level,
        "input_features": machine_input.iloc[0].to_dict()
    }

    return result


