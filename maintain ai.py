import numpy as np


def retrieve_maintenance_evidence(
    query,
    top_k=3,
    min_score=0.20
):
    """
    Retrieve the most relevant maintenance-document
    chunks for a natural-language query.

    Parameters
    ----------
    query : str
        Maintenance question or situation.
    top_k : int
        Number of results to return.
    min_score : float
        Minimum cosine-similarity score.

    Returns
    -------
    list
        Ranked evidence chunks.
    """

    if not query or not query.strip():
        return []

    # Create embedding for the query
    query_embedding = embedding_model.encode(
        [query],
        convert_to_numpy=True,
        normalize_embeddings=True
    )[0]

    query_embedding = np.asarray(
        query_embedding,
        dtype=np.float32
    )

    # Since both query and document embeddings are normalized,
    # dot product = cosine similarity.
    similarity_scores = np.dot(
        rag_embeddings,
        query_embedding
    )

    # Rank from highest to lowest similarity
    ranked_indices = np.argsort(
        similarity_scores
    )[::-1]

    results = []

    for index in ranked_indices:
        score = float(similarity_scores[index])

        if score < min_score:
            continue

        chunk = rag_chunks[index]

        results.append({
            "rank": len(results) + 1,
            "score": round(score, 4),
            "doc_id": chunk["doc_id"],
            "chunk_id": chunk["chunk_id"],
            "filename": chunk["filename"],
            "text": chunk["text"]
        })

        if len(results) >= top_k:
            break

    return results


