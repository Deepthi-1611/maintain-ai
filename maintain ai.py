import gradio as gr


def format_maintenai_result(
    machine_type,
    air_temperature,
    process_temperature,
    rotational_speed,
    torque,
    tool_wear
):
    """
    Run the final MaintenAI pipeline and convert
    the structured result into an evaluator-friendly
    Markdown report.
    """

    try:

        result = run_final_maintenai(
            machine_type=machine_type,
            air_temperature=float(air_temperature),
            process_temperature=float(process_temperature),
            rotational_speed=float(rotational_speed),
            torque=float(torque),
            tool_wear=float(tool_wear)
        )

        # ----------------------------------------
        # ML
        # ----------------------------------------

        ml = result.ml_result

        prediction = (
            "FAILURE"
            if ml["predicted_failure"]
            else "NORMAL"
        )

        # ----------------------------------------
        # Bayesian
        # ----------------------------------------

        bayesian = result.bayesian_result

        if bayesian.get("most_likely_fault"):

            leading_fault = bayesian[
                "most_likely_fault"
            ]

            leading_probability = bayesian[
                "probability_percent"
            ]

        else:

            leading_fault = "Not available"
            leading_probability = 0

        # ----------------------------------------
        # Evidence
        # ----------------------------------------

        evidence_lines = (
            "\n".join(
                [
                    f"- `{item}`"
                    for item in result.observed_evidence
                ]
            )
            if result.observed_evidence
            else "- No threshold-based abnormal evidence detected."
        )

        # ----------------------------------------
        # Bayesian probabilities
        # ----------------------------------------

        bayesian_lines = ""

        if bayesian.get(
            "all_fault_probabilities"
        ):

            for fault, probability in bayesian[
                "all_fault_probabilities"
            ].items():

                bayesian_lines += (
                    f"- **{fault}**: {probability:.2f}%\n"
                )

        else:

            bayesian_lines = (
                "- Bayesian analysis unavailable.\n"
            )

        # ----------------------------------------
        # RAG sources
        # ----------------------------------------

        rag_lines = ""

        for item in result.rag_result.get(
            "evidence",
            []
        ):

            score = item.get(
                "hybrid_score",
                item.get("score", 0)
            )

            rag_lines += (
                f"- **{item['doc_id']}** — "
                f"{item['filename']} "
                f"(score: {score:.4f})\n"
            )

        if not rag_lines:

            rag_lines = "- No relevant sources retrieved.\n"

        # ----------------------------------------
        # A* alternatives
        # ----------------------------------------

        alternative_lines = ""

        for item in result.maintenance_plan.get(
            "alternative_diagnostic_paths",
            []
        ):

            alternative_lines += (
                f"- **{item['fault']}**: "
                f"`{' → '.join(item['path'])}` "
                f"(cost: {item['cost']})\n"
            )

        if not alternative_lines:

            alternative_lines = "- None.\n"

        # ----------------------------------------
        # Maintenance plan
        # ----------------------------------------

        plan_lines = ""

        for step in result.maintenance_plan.get(
            "steps",
            []
        ):

            plan_lines += (
                f"{step['step']}. "
                f"**{step['action']}** — "
                f"{step['description']} "
                f"({step['estimated_minutes']} min)\n"
            )

        if not plan_lines:

            plan_lines = "No specific maintenance plan generated.\n"

        # ----------------------------------------
        # Final report
        # ----------------------------------------

        report = f"""
# 🛠️ MaintenAI Assessment

## Machine Condition

| Parameter | Value |
|---|---:|
| Machine Type | {machine_type} |
| Air Temperature | {float(air_temperature):.2f} |
| Process Temperature | {float(process_temperature):.2f} |
| Rotational Speed | {float(rotational_speed):.2f} RPM |
| Torque | {float(torque):.2f} |
| Tool Wear | {float(tool_wear):.2f} |

## 🤖 ML Fault Analysis

**Prediction:** `{prediction}`

**Failure Probability:** `{ml["failure_probability_percent"]:.2f}%`

**Risk Level:** `{ml["risk_level"]}`

## 🔎 Observed Evidence

{evidence_lines}

## 🧮 Bayesian Uncertainty

**Leading Hypothesis:** `{leading_fault}`

**Prototype Probability:** `{leading_probability:.2f}%`

{bayesian_lines}

## 🕸️ Knowledge Graph Reasoning

"""

        if result.kg_result:

            for evidence, faults in result.kg_result.items():

                report += (
                    f"**{evidence}**\n\n"
                )

                for item in faults:

                    report += (
                        f"- Possible relationship → "
                        f"`{item['fault']}`\n"
                    )

                report += "\n"

        else:

            report += (
                "No Knowledge Graph relationships found.\n\n"
            )

        report += f"""
## 📚 Hybrid RAG Evidence

{rag_lines}

## 🔎 A* Diagnostic Alternatives

{alternative_lines}

## 📋 Recommended Maintenance Plan

{plan_lines}

**Estimated effort:** "
{result.maintenance_plan.get(
    "total_estimated_minutes",
    0
)} minutes

## 🧑‍💼 Supervisor Assessment

{result.final_explanation}

---

### ⚠️ Decision-Support Notice

This academic prototype provides model estimates and
retrieved knowledge to support maintenance reasoning.
It does not confirm physical faults and does not replace
qualified engineering inspection or manufacturer procedures.
"""

        return report

    except Exception as error:

        return (
            "## ❌ MaintenAI Error\n\n"
            f"`{str(error)}`"
        )


