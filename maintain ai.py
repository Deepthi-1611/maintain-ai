# ------------------------------------------------
# Generate a maintenance plan
# ------------------------------------------------

def generate_maintenance_plan(
    fault,
    diagnostic_actions,
    evidence=None
):
    """
    Generate a structured maintenance plan.

    The planner:
    1. Starts with safety isolation.
    2. Adds diagnostic actions associated with the fault.
    3. Ensures prerequisite relationships.
    4. Adds verification and maintenance recording.
    5. Produces a topologically ordered plan.

    Parameters
    ----------
    fault : str
        Most relevant fault hypothesis.

    diagnostic_actions : list
        Candidate maintenance actions.

    evidence : list, optional
        Observed evidence.

    Returns
    -------
    dict
        Structured maintenance plan.
    """

    if evidence is None:
        evidence = []

    # Start with safety
    selected_actions = {
        "SafetyIsolation"
    }

    # Add valid diagnostic actions
    for action in diagnostic_actions:

        if action in ACTION_DETAILS:
            selected_actions.add(action)

    # Add prerequisites recursively
    changed = True

    while changed:

        changed = False

        for action in list(selected_actions):

            prerequisites = ACTION_DETAILS[
                action
            ]["prerequisites"]

            for prerequisite in prerequisites:

                if prerequisite not in selected_actions:

                    selected_actions.add(
                        prerequisite
                    )

                    changed = True

    # Add final verification and record keeping
    selected_actions.add("VerificationTest")
    selected_actions.add("RecordMaintenance")

    # Build a temporary subgraph
    plan_graph = PLANNING_GRAPH.subgraph(
        selected_actions
    ).copy()

    # Ensure final actions are after diagnostic actions
    for action in selected_actions:

        if action not in [
            "SafetyIsolation",
            "VerificationTest",
            "RecordMaintenance"
        ]:

            plan_graph.add_edge(
                action,
                "VerificationTest",
                relation="must_precede"
            )

    # Topological ordering
    try:
        ordered_actions = list(
            nx.topological_sort(plan_graph)
        )

    except nx.NetworkXUnfeasible:

        raise RuntimeError(
            "Planning graph contains a dependency cycle."
        )

    # Create detailed plan steps
    plan_steps = []

    total_duration = 0

    for step_number, action in enumerate(
        ordered_actions,
        start=1
    ):

        details = ACTION_DETAILS[action]

        total_duration += details["duration"]

        plan_steps.append({
            "step": step_number,
            "action": action,
            "description": details["description"],
            "estimated_minutes": details["duration"]
        })

    return {
        "fault_hypothesis": fault,
        "evidence": evidence,
        "steps": plan_steps,
        "total_estimated_minutes": total_duration,
        "human_review_required": True,
        "planning_note": (
            "Action ordering is generated from prototype "
            "prerequisite relationships. It is a planning "
            "demonstration, not a manufacturer-approved procedure."
        )
    }


