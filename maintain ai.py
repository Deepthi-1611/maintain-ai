def generate_fault_focused_plan(
    fault_hypothesis,
    observed_evidence,
    search_results=None
):
    """
    Generate a maintenance plan focused on the
    leading fault hypothesis.

    Alternative A* paths are retained as diagnostic
    alternatives but are NOT automatically inserted
    into the final action plan.
    """

    # ----------------------------------------
    # Get actions specifically associated
    # with the leading fault
    # ----------------------------------------

    fault_actions = [
        item["action"]
        for item in kg_find_actions_for_fault(
            fault_hypothesis
        )
    ]

    # ----------------------------------------
    # Generate focused plan
    # ----------------------------------------

    focused_plan = generate_maintenance_plan(
        fault=fault_hypothesis,
        diagnostic_actions=fault_actions,
        evidence=observed_evidence
    )

    # ----------------------------------------
    # Keep alternative search paths separately
    # ----------------------------------------

    alternatives = []

    if search_results:

        for result in search_results:

            if result.get("fault") != fault_hypothesis:

                alternatives.append({
                    "fault": result.get("fault"),
                    "path": result.get("path"),
                    "cost": result.get("cost")
                })

    focused_plan["alternative_diagnostic_paths"] = (
        alternatives
    )

    focused_plan["planning_note"] = (
        "The final action plan is based on the leading "
        "fault hypothesis. Alternative A* paths are "
        "reported separately and are not automatically "
        "added to the maintenance plan."
    )

    return focused_plan


