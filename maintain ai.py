def retrieve_hybrid_evidence_v2(
    query,
    fault_hypothesis=None,
    top_k=3
):
    """
    Improved HybridRAG retrieval.

    Combines:
    - semantic similarity
    - fault-specific document priority
    - keyword relevance

    The most domain-specific document receives
    the strongest knowledge bonus.
    """

    # Retrieve a broad semantic candidate set
    semantic_results = retrieve_maintenance_evidence(
        query=query,
        top_k=len(rag_chunks)
    )

    priority_map = FAULT_DOCUMENT_PRIORITY.get(
        fault_hypothesis,
        {}
    )

    reranked = []

    for item in semantic_results:

        semantic_score = float(
            item["score"]
        )

        doc_id = item["doc_id"]

        # ----------------------------------------
        # Domain-specific priority
        # ----------------------------------------

        if doc_id in priority_map:

            priority = priority_map[doc_id]

            if priority == 1:
                knowledge_bonus = 0.35
            elif priority == 2:
                knowledge_bonus = 0.22
            elif priority == 3:
                knowledge_bonus = 0.12
            else:
                knowledge_bonus = 0.05

        else:
            priority = None
            knowledge_bonus = 0.0

        # ----------------------------------------
        # Keyword relevance
        # ----------------------------------------

        keyword_bonus = 0.0

        if fault_hypothesis:

            query_terms = set(
                fault_hypothesis
                .replace("Fault", "")
                .replace("Wear", "")
                .lower()
                .split()
            )

            text_lower = item[
                "text"
            ].lower()

            matching_terms = sum(
                1
                for term in query_terms
                if term and term in text_lower
            )

            keyword_bonus = min(
                matching_terms * 0.05,
                0.15
            )

        # ----------------------------------------
        # Final score
        # ----------------------------------------
        #
        # Semantic relevance remains important,
        # but domain-specific knowledge gets priority.
        # ----------------------------------------

        hybrid_score = (
            0.60 * semantic_score
            + 0.30 * knowledge_bonus
            + 0.10 * keyword_bonus
        )

        reranked.append({
            **item,
            "semantic_score": round(
                semantic_score,
                4
            ),
            "knowledge_bonus": round(
                knowledge_bonus,
                4
            ),
            "keyword_bonus": round(
                keyword_bonus,
                4
            ),
            "document_priority": priority,
            "hybrid_score": round(
                hybrid_score,
                4
            )
        })

    # Sort by hybrid score
    reranked.sort(
        key=lambda item: item["hybrid_score"],
        reverse=True
    )

    # Assign final ranks
    final_results = []

    for rank, item in enumerate(
        reranked[:top_k],
        start=1
    ):
        result = dict(item)
        result["rank"] = rank
        final_results.append(result)

    return final_results


