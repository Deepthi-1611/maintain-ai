def maintenai_ui_dashboard(
    machine_type,
    air_temp,
    process_temp,
    rotational_speed,
    torque,
    tool_wear,
    natural_query
):
    # 1. Run Enhanced Analysis (ML + Bayesian + Evidence)
    try:
        analysis = analyze_machine_condition_v2(
            machine_type=machine_type,
            air_temperature=air_temp,
            process_temperature=process_temp,
            rotational_speed=rotational_speed,
            torque=torque,
            tool_wear=tool_wear
        )
    except Exception as e:
        analysis = None

    # Format ML Results
    if analysis:
        ml = analysis["ml_prediction"]
        status_text = f"RESULT: {'⚠️ FAILURE' if ml['predicted_failure'] else '✅ NORMAL'} | Probability: {ml['failure_probability_percent']:.2f}% | Risk: {ml['risk_level']}"
        observed_ev = analysis["observed_evidence"]
        bayesian = analysis["bayesian_analysis"]

        # Leading fault
        leading_fault = bayesian["most_likely_fault"] if bayesian else "BearingWear"
        bayesian_summary = "\n".join([f"• {f}: {p:.2f}%" for f, p in bayesian["all_fault_probabilities"].items()]) if bayesian else "No abnormal evidence."
    else:
        status_text = "Analysis unavailable."
        observed_ev = []
        leading_fault = "BearingWear"
        bayesian_summary = "N/A"

    # 2. Run Hybrid RAG & Planning
    try:
        plan_result = build_evidence_backed_plan(
            machine_type=machine_type,
            observed_evidence=observed_ev,
            fault_hypothesis=leading_fault,
            top_k=2
        )
        plan_steps_text = "\n".join([
            f"Step {s['step']}: {s['action']} — {s['description']} ({s['estimated_minutes']} min)"
            for s in plan_result["maintenance_plan"]["steps"]
        ])
        total_effort = f"{plan_result['maintenance_plan']['total_estimated_minutes']} minutes"

        retrieved_docs_text = "\n\n".join([
            f"[{item['doc_id']}] (Score: {item.get('hybrid_score', item['score']):.2f}) {item['filename']}\n{item['text']}"
            for item in plan_result["retrieved_evidence"]
        ])
    except Exception as e:
        plan_steps_text = f"Planning error: {e}"
        total_effort = "N/A"
        retrieved_docs_text = "No retrieved evidence."

    # 3. Run Gemini Grounded RAG for Custom Natural Query
    query_to_use = natural_query if natural_query and natural_query.strip() else f"Machine shows {', '.join(observed_ev) if observed_ev else 'normal readings'}. What should be checked?"
    try:
        rag_answer = generate_rag_answer(query=query_to_use, top_k=2)
        gemini_response_text = rag_answer["answer"]
    except Exception as e:
        gemini_response_text = f"Could not generate LLM response: {e}"

    return (
        status_text,
        ", ".join(observed_ev) if observed_ev else "None (Normal operating envelope)",
        leading_fault,
        bayesian_summary,
        plan_steps_text,
        total_effort,
        retrieved_docs_text,
        gemini_response_text
    )

