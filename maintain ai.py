def generate_hybrid_rag_answer(
    query,
    fault_hypothesis=None,
    top_k=3
):
    """
    Generate an evidence-grounded Gemini response
    using the improved HybridRAG retriever.
    """

    # ----------------------------------------
    # 1. Hybrid retrieval
    # ----------------------------------------

    evidence = retrieve_hybrid_evidence_v2(
        query=query,
        fault_hypothesis=fault_hypothesis,
        top_k=top_k
    )

    if not evidence:
        return {
            "query": query,
            "fault_hypothesis": fault_hypothesis,
            "answer": (
                "No sufficiently relevant maintenance evidence "
                "was found in the knowledge base."
            ),
            "evidence": []
        }

    # ----------------------------------------
    # 2. Build evidence context
    # ----------------------------------------

    evidence_blocks = []

    for item in evidence:

        evidence_blocks.append(
            f"""
SOURCE: {item['doc_id']}
TITLE: {item['filename']}
HYBRID SCORE: {item['hybrid_score']}

EVIDENCE:
{item['text']}
""".strip()
        )

    evidence_context = "\n\n".join(
        evidence_blocks
    )

    # ----------------------------------------
    # 3. Grounded LLM prompt
    # ----------------------------------------

    prompt = f"""
You are MaintenAI, an industrial maintenance
decision-support assistant.

Use ONLY the retrieved evidence below.

Do not invent procedures.
Do not claim that a fault is confirmed.
Do not create technical specifications that
are not present in the evidence.

Clearly distinguish:
- observed machine information
- possible fault hypotheses
- recommended inspections
- limitations and uncertainty

USER QUERY:
{query}

FAULT HYPOTHESIS:
{fault_hypothesis if fault_hypothesis else "Not specified"}

RETRIEVED EVIDENCE:
{evidence_context}

Return the response using this structure:

LIKELY INTERPRETATION:
Give a concise interpretation.

RECOMMENDED INSPECTIONS:
Give the relevant inspection steps supported
by the retrieved evidence.

WHY:
Explain how the evidence supports the recommendation.

CAUTION:
State that this is decision support and requires
qualified human review before physical maintenance.
"""

    # ----------------------------------------
    # 4. Gemini generation
    # ----------------------------------------

    try:

        response = client.models.generate_content(
            model=GEMINI_MODEL,
            contents=prompt
        )

        answer = response.text.strip()

    except Exception as error:

        answer = (
            "Gemini could not generate the explanation. "
            "The retrieved evidence is still available.\n\n"
            f"Error: {error}"
        )

    return {
        "query": query,
        "fault_hypothesis": fault_hypothesis,
        "answer": answer,
        "evidence": evidence
    }


